"""Provider-neutral, raw-evidence gateway contracts for M5 execution."""

from __future__ import annotations

from collections.abc import Mapping
from enum import StrEnum
from typing import Protocol, Self, TypeAlias
from uuid import UUID

from pydantic import Field, model_validator

from agent_factory.domain.common import (
    FrozenJsonObject,
    FrozenModel,
    JsonObject,
    Sha256,
)
from experiments.contracts import GenerationConfig


class GatewayFailureKind(StrEnum):
    NETWORK = "network"
    RATE_LIMITED = "rate-limited"
    SERVER_ERROR = "server-error"
    CLIENT_ERROR = "client-error"
    TIMED_OUT = "timed-out"
    FILTERED = "filtered"
    INVALID_RESPONSE = "invalid-response"


class GatewayRequest(FrozenModel):
    run_id: UUID
    attempt_number: int = Field(ge=1, le=3)
    generation: GenerationConfig
    invocation: JsonObject
    expected_output_schema: JsonObject
    prompt_hash: Sha256


class GatewaySuccess(FrozenModel):
    provider_request_id: str = Field(min_length=1, max_length=256)
    raw_response: JsonObject
    output_text: str = Field(min_length=1, max_length=256_000)
    structured_output: JsonObject
    prompt_tokens: int = Field(ge=0)
    completion_tokens: int = Field(ge=0)


class GatewayFailure(FrozenModel):
    kind: GatewayFailureKind
    error_code: str = Field(
        min_length=1,
        max_length=128,
        pattern=r"^[A-Z][A-Z0-9_]*$",
    )
    provider_request_id: str | None = Field(default=None, min_length=1, max_length=256)
    raw_response: JsonObject | None = None
    prompt_tokens: int | None = Field(default=None, ge=0)
    completion_tokens: int | None = Field(default=None, ge=0)

    @model_validator(mode="after")
    def usage_must_be_complete_when_present(self) -> Self:
        if (self.prompt_tokens is None) != (self.completion_tokens is None):
            raise ValueError("gateway failure usage must provide both token counts")
        return self


GatewayOutcome: TypeAlias = GatewaySuccess | GatewayFailure


class ExperimentGateway(Protocol):
    """Perform one bounded provider request and retain raw evidence."""

    @property
    def is_live(self) -> bool:
        """Declare whether calls can leave the local process."""

        ...

    async def generate(self, request: GatewayRequest) -> GatewayOutcome:
        """Return a normalized success or provider failure."""


class FakeExperimentGateway:
    """Deterministic scripted gateway used by tests and offline smoke runs."""

    is_live = False

    def __init__(
        self,
        script: Mapping[tuple[UUID, int], GatewayOutcome] | None = None,
    ) -> None:
        self._script = dict(script or {})
        self._calls: list[GatewayRequest] = []

    @property
    def calls(self) -> tuple[GatewayRequest, ...]:
        return tuple(self._calls)

    async def generate(self, request: GatewayRequest) -> GatewayOutcome:
        self._calls.append(request)
        scripted = self._script.get((request.run_id, request.attempt_number))
        if scripted is not None:
            return scripted
        structured = FrozenJsonObject(
            {
                "title": "Synthetic offline result",
                "summary": "Generated by FakeExperimentGateway without network I/O.",
                "key_points": ["offline", "deterministic"],
                "next_action": "Use only for executor verification.",
            }
        )
        return GatewaySuccess(
            provider_request_id=(f"fake-{request.run_id}-{request.attempt_number}"),
            raw_response={
                "provider": "fake",
                "attempt": request.attempt_number,
                "output": structured,
            },
            output_text=(
                '{"title":"Synthetic offline result","summary":"Generated by '
                'FakeExperimentGateway without network I/O.","key_points":'
                '["offline","deterministic"],"next_action":"Use only for '
                'executor verification."}'
            ),
            structured_output=structured,
            prompt_tokens=100,
            completion_tokens=40,
        )
